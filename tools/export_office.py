HEADER_FILL = PatternFill("solid", fgColor="1F4E79")
HEADER_FONT = Font(bold=True, color="FFFFFF", name="Calibri", size=11)
TITLE_FONT = Font(bold=True, name="Calibri", size=14, color="1F4E79")
SECTION_FONT = Font(bold=True, name="Calibri", size=12, color="2E75B6")
CELL_FONT = Font(name="Calibri", size=11)
THIN = Border(
    left=Side(style="thin", color="B0B0B0"),
    right=Side(style="thin", color="B0B0B0"),
    top=Side(style="thin", color="B0B0B0"),
    bottom=Side(style="thin", color="B0B0B0"),
)
WRAP = Alignment(wrap_text=True, vertical="top")


def style_header(ws, row: int, cols: int) -> None:
    for c in range(1, cols + 1):
        cell = ws.cell(row, c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = WRAP
        cell.border = THIN


def style_body(ws, r0: int, r1: int, cols: int) -> None:
    for r in range(r0, r1 + 1):
        for c in range(1, cols + 1):
            cell = ws.cell(r, c)
            cell.font = CELL_FONT
            cell.alignment = WRAP
            cell.border = THIN


def autosize(ws, widths: list[int]) -> None:
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def put_title(ws, text: str, cols: int = 1) -> int:
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=max(cols, 1))
    ws.cell(1, 1, text).font = TITLE_FONT
    ws.row_dimensions[1].height = 22
    return 2


def put_section(ws, row: int, text: str, cols: int = 1) -> int:
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=max(cols, 1))
    ws.cell(row, 1, text).font = SECTION_FONT
    return row + 1


def put_table(ws, row: int, headers: list[str], data: list[list]) -> int:
    cols = len(headers)
    for c, h in enumerate(headers, 1):
        ws.cell(row, c, h)
    style_header(ws, row, cols)
    row += 1
    start = row
    for item in data:
        for c, val in enumerate(item, 1):
            ws.cell(row, c, val)
        row += 1
    if data:
        style_body(ws, start, row - 1, cols)
    return row + 1


